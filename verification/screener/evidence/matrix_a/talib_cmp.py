"""Compare the terminal TS outputs (data/<T>.ts.json) with TA-Lib 0.6.8 (C 0.6.4) for I01-I27."""
import json, sys, os, math
import numpy as np, talib
HERE = os.path.dirname(os.path.abspath(__file__))
assert talib.__version__ == '0.6.8' and talib.__ta_version__.startswith(b'0.6.4 ')
def arr(s): return np.array([np.nan if v is None else v for v in s], dtype=float)
def cmp(ts, tl):
    ts, tl = arr(ts), np.asarray(tl, dtype=float)
    a_ok, b_ok = np.isfinite(ts), np.isfinite(tl)
    fa = int(np.argmax(a_ok)) if a_ok.any() else -1
    fb = int(np.argmax(b_ok)) if b_ok.any() else -1
    both = a_ok & b_ok
    d = np.abs(ts[both] - tl[both]); m = np.maximum(np.abs(ts[both]), np.abs(tl[both]))
    r = np.where(m > 0, d / np.where(m > 0, m, 1), 0)
    # absolute diff relative to series scale (for oscillators crossing 0)
    scale = np.nanmax(np.abs(tl[b_ok])) if b_ok.any() else 1
    return dict(ts_first=fa, tl_first=fb, null_mismatch=int((a_ok != b_ok).sum()), compared=int(both.sum()),
                max_rel=float(r.max()) if r.size else 0.0, max_abs_over_scale=float(d.max() / scale) if d.size and scale else 0.0,
                n_rel_gt_1e9=int((r > 1e-9).sum()))
def sma_np(x, n):
    return talib.SMA(x, timeperiod=n)
rows = []
for t in sys.argv[1:]:
    D = json.load(open(os.path.join(HERE, 'data', t + '.ts.json')))
    B, O = D['bars'], D['out']
    o, h, l, c, v = (arr(B[k]) for k in 'OHLCV')
    hl2 = (h + l) / 2; hlc3 = (h + l + c) / 3
    def add(iid, out, ts, tl, note=''):
        rows.append(dict(ticker=t, id=iid, output=out, note=note, **cmp(ts, tl)))
    add('I01', 'sma', O['sma']['sma'], talib.SMA(c, 20))
    add('I02', 'ema', O['ema']['ema'], talib.EMA(c, 20))
    add('I03', 'wma', O['wma']['wma'], talib.WMA(c, 20))
    add('I03', 'wma(hlc3,9)', O['wma_hlc3']['wma'], talib.WMA(hlc3, 9))
    hma_tl = talib.WMA(2 * talib.WMA(c, 4) - talib.WMA(c, 9), 3)
    add('I04', 'hma', O['hma']['hma'], hma_tl, 'composed from talib.WMA (no TA-Lib HMA)')
    add('I05', 'kama', O['kama']['kama'], talib.KAMA(c, 10))
    add('I05', 'kama(hl2,5)', O['kama_alt']['kama'], talib.KAMA(hl2, 5))
    m, s, hh = talib.MACD(c, 12, 26, 9)
    add('I06', 'macd vs talib.MACD', O['macd']['macd'], m, 'TA-Lib MACD seeds the fast EMA at the slow lookback')
    add('I06', 'signal vs talib.MACD', O['macd']['signal'], s)
    add('I06', 'histogram vs talib.MACD', O['macd']['histogram'], hh)
    me, se, he = talib.MACDEXT(c, 12, 1, 26, 1, 9, 1)
    add('I06', 'macd vs talib.MACDEXT(EMA)', O['macd']['macd'], me)
    add('I06', 'signal vs talib.MACDEXT(EMA)', O['macd']['signal'], se)
    mm = talib.EMA(c, 12) - talib.EMA(c, 26); sg = np.full(len(c), np.nan)
    if len(c) >= 26: sg[25:] = talib.EMA(mm[25:], 9)
    add('I06', 'macd vs F04 method', O['macd']['macd'], mm)
    add('I06', 'signal vs F04 method', O['macd']['signal'], sg)
    add('I06', 'histogram vs F04 method', O['macd']['histogram'], mm - sg)
    add('I07', 'adx', O['adx']['adx'], talib.ADX(h, l, c, 14))
    add('I07', 'plus_di', O['adx']['plus_di'], talib.PLUS_DI(h, l, c, 14))
    add('I07', 'minus_di', O['adx']['minus_di'], talib.MINUS_DI(h, l, c, 14))
    add('I07', 'adx 7/7', O['adx_7']['adx'], talib.ADX(h, l, c, 7))
    add('I07', 'adx 14/7 vs talib.ADX(7)', O['adx_14_7']['adx'], talib.ADX(h, l, c, 7), 'no TA-Lib equivalent when di_length != adx_smoothing')
    dn, up = talib.AROON(h, l, 14)
    add('I08', 'aroon_up', O['aroon']['aroon_up'], up); add('I08', 'aroon_down', O['aroon']['aroon_down'], dn)
    add('I10', 'upper', O['donchian']['upper'], talib.MAX(h, 20)); add('I10', 'lower', O['donchian']['lower'], talib.MIN(l, 20))
    add('I10', 'basis', O['donchian']['basis'], (talib.MAX(h, 20) + talib.MIN(l, 20)) / 2)
    ke = talib.EMA(c, 20); ka = talib.ATR(h, l, c, 10)
    add('I11', 'basis', O['keltner']['basis'], ke, 'composed EMA(20)+-2*ATR(10)')
    add('I11', 'upper', O['keltner']['upper'], ke + 2 * ka); add('I11', 'lower', O['keltner']['lower'], ke - 2 * ka)
    sar = talib.SAR(h, l, 0.02, 0.2)
    add('I12', 'sar', O['psar']['sar'], sar)
    ts_dir = arr(O['psar']['direction']); sx = talib.SAREXT(h, l, 0, 0, 0.02, 0.02, 0.2, 0.02, 0.02, 0.2)
    add('I12', 'direction vs sign(SAREXT)', ts_dir, np.sign(sx))
    sx2 = talib.SAREXT(h, l, 0, 0, 0.01, 0.03, 0.25, 0.01, 0.03, 0.25)
    add('I12', 'sar alt 0.01/0.03/0.25 vs |SAREXT|', O['psar_alt']['sar'], np.abs(sx2))
    add('I13', 'rsi', O['rsi']['rsi'], talib.RSI(c, 14))
    fk, fd = talib.STOCHRSI(c, 14, 14, 3, 0)
    fk1, _ = talib.STOCHRSI(c, 14, 14, 1, 0)
    k_ref = talib.SMA(fk1, 3); d_ref = talib.SMA(k_ref, 3)
    add('I14', 'k vs SMA3(STOCHRSI fastk)', O['stoch_rsi']['k'], k_ref)
    add('I14', 'd vs SMA3(SMA3(fastk))', O['stoch_rsi']['d'], d_ref)
    add('I14', 'k vs talib STOCHRSI fastk (raw)', O['stoch_rsi']['k'], fk, 'convention differs: TA-Lib fastk is unsmoothed')
    add('I14', 'k vs talib STOCHRSI fastd', O['stoch_rsi']['k'], fd, 'TA-Lib fastd(3,SMA) = SMA3(fastk) = terminal K')
    sk, sd = talib.STOCH(h, l, c, 14, 3, 0, 3, 0)
    add('I15', 'k', O['stochastic']['k'], sk); add('I15', 'd', O['stochastic']['d'], sd)
    sk2, sd2 = talib.STOCH(h, l, c, 5, 1, 0, 3, 0)
    add('I15', 'k 5/1/3', O['stochastic_5_1_3']['k'], sk2); add('I15', 'd 5/1/3', O['stochastic_5_1_3']['d'], sd2)
    add('I16', 'williams_r', O['williams_r']['williams_r'], talib.WILLR(h, l, c, 14))
    add('I17', 'roc', O['roc']['roc'], talib.ROC(c, 9))
    add('I18', 'momentum', O['momentum']['momentum'], talib.MOM(c, 10))
    add('I19', 'cci', O['cci']['cci'], talib.CCI(h, l, c, 20)); add('I19', 'cci 14', O['cci_14']['cci'], talib.CCI(h, l, c, 14))
    add('I20', 'cmo vs talib.CMO', O['cmo']['cmo'], talib.CMO(c, 14), 'convention differs: TA-Lib CMO Wilder-smooths')
    dc = np.diff(c, prepend=np.nan); g = talib.SUM(np.where(dc > 0, dc, 0.0)[1:], 14); ls = talib.SUM(np.where(dc < 0, -dc, 0.0)[1:], 14)
    plain = np.concatenate([[np.nan], 100 * (g - ls) / (g + ls)])
    add('I20', 'cmo vs plain-sum (talib.SUM)', O['cmo']['cmo'], plain)
    add('I22', 'trix', O['trix']['trix'], talib.TRIX(c, 15))
    add('I23', 'uo', O['ultimate_osc']['uo'], talib.ULTOSC(h, l, c, 7, 14, 28))
    add('I23', 'uo 5/10/20', O['uo_alt']['uo'], talib.ULTOSC(h, l, c, 5, 10, 20))
    mp = talib.MEDPRICE(h, l)
    add('I24', 'ao', O['awesome_osc']['ao'], talib.SMA(mp, 5) - talib.SMA(mp, 34), 'composed MEDPRICE+SMA')
    pp = talib.PPO(c, 12, 26, 1); ps = np.full(len(c), np.nan)
    fv = np.where(np.isfinite(pp))[0]
    if fv.size: ps[fv[0]:] = talib.EMA(pp[fv[0]:], 9)
    add('I25', 'ppo vs PPO(matype=1)', O['ppo']['ppo'], pp); add('I25', 'signal vs EMA9(PPO)', O['ppo']['signal'], ps)
    add('I25', 'histogram', O['ppo']['histogram'], pp - ps)
    add('I25', 'ppo vs PPO default matype=0', O['ppo']['ppo'], talib.PPO(c, 12, 26), 'TA-Lib default is SMA')
    pp2 = talib.PPO(c, 5, 20, 1); ps2 = np.full(len(c), np.nan); fv2 = np.where(np.isfinite(pp2))[0]
    if fv2.size: ps2[fv2[0]:] = talib.EMA(pp2[fv2[0]:], 4)
    add('I25', 'ppo 5/20/4', O['ppo_5_20_4']['ppo'], pp2); add('I25', 'signal 5/20/4', O['ppo_5_20_4']['signal'], ps2)
    add('I26', 'bop', O['bop']['bop'], talib.BOP(o, h, l, c))
    u, mi, lo = talib.BBANDS(c, 20, 2.0, 2.0, 0)
    add('I27', 'upper', O['bollinger']['upper'], u); add('I27', 'basis', O['bollinger']['basis'], mi); add('I27', 'lower', O['bollinger']['lower'], lo)
    u2, m2, l2 = talib.BBANDS(c, 20, 2.0, 2.0, 1)
