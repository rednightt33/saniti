import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
const b = await chromium.launch(); const p = await b.newPage({ viewport:{ width:1600, height:960 } });
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()) });
await p.addInitScript(() => { localStorage.clear(); localStorage.setItem('ml.symbol','MAPI'); localStorage.setItem('ml.broker.collapsed','0'); localStorage.setItem('ml.win.open', JSON.stringify(['acc'])) });
await p.goto('http://127.0.0.1:18901/terminal-app/'); await p.waitForSelector('#chart canvas'); await p.waitForTimeout(4500);
const R = {};
R.select = await p.$eval('#accBoard', s => [...s.options].map(o => o.text).join('/') + ' = ' + s.value).catch(e => 'none');
R.panelRows = await p.$$eval('#accBody .pa-row', r => r.length);
R.panelParts = await p.$$eval('#accBody .fill.split', f => f.slice(0, 4).map(x => [...x.children].map(i => i.className + ' ' + i.style.width).join(',')));
R.legend = await p.$eval('#accBody .acc-leg', e => e.innerText.replace(/\s+/g, ' ')).catch(() => 'none');
R.tip = await p.$eval('#accBody .pa-b[data-b]', e => e.dataset.tip);
const first = await p.$eval('#accBody .pa-row', e => e.innerText.replace(/\s+/g, ' '));
await p.selectOption('#accBoard', 'Nego'); await p.waitForTimeout(200);
R.nego = [first, await p.$eval('#accBody', e => e.innerText.replace(/\s+/g, ' ').slice(0, 80))];
await p.selectOption('#accBoard', 'All');
R.window = await p.$$eval('.pw-acc .fill.split', f => f.length).catch(() => 0);
R.windowFoot = await p.$eval('.pw-acc', e => e.closest('.fw-body, .pw-body, div').parentElement.querySelector('.pw-foot')?.innerText).catch(() => 'n/a');
await p.screenshot({ path:'shots/tsplit.png' });
R.errors = errs; console.log(JSON.stringify(R, null, 1)); await b.close();
