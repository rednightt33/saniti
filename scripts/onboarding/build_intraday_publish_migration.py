#!/usr/bin/env python3
"""Build database/migrations/20261101_001_intraday_publish.sql (EXEC-INTRADAY-FEATURES C1, user decisions 2026-11-01:
C7.4 A "loader menulis catatan kecil per (saham, timeframe)", and one definition of bars_per_year for Feature 01
intraday and the Terminal publisher).

The Feature 01 function is copied from migration 20261031_004 (whose body equals the live prosrc, checked 2026-11-01)
with its inline bars_per_year statement replaced by a call of the new shared function; the script refuses when the
statement it replaces is not found exactly once.

  python3 scripts/onboarding/build_intraday_publish_migration.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'database/migrations/20261031_004_intraday_features.sql'
OUT = ROOT / 'database/migrations/20261101_001_intraday_publish.sql'

INLINE = """    SELECT round(252 * avg(index_bars))::integer INTO v_bars_per_year
      FROM public.price_stock_idx_intraday_quality
     WHERE timeframe = p_timeframe AND status = 'COMPLETE' AND index_bars > 0;
"""
CALL = """    v_bars_per_year := public.intraday_bars_per_year(p_timeframe);
"""

HEAD = """-- EXEC-INTRADAY-FEATURES C1 (user 2026-11-01: "Opsi 1, 4A, 2A dan 3A ok"; go: "Kenapa kita nggak langsung deploy
-- saja?"). Generated by scripts/onboarding/build_intraday_publish_migration.py.
-- * intraday_bars_per_year(timeframe): the one definition of bars per year of an intraday timeframe (252 x the mean
--   IHSG bars of the COMPLETE sessions in price_stock_idx_intraday_quality), used by refresh_feature_01_stock_intraday
--   (replaced below: the same body, the inline statement now a call) and by terminal-publisher (manifest).
-- * intraday_publish_change: per (ticker, timeframe) the first bar idx-intraday-cron wrote since the last publication,
--   written in the same statement as the bars (apps/idx-price-cron/intraday_update.py), IHSG included; the publisher
--   republishes only those series (C7.4 A), without reading the whole bar table (ERRORS M319).
-- * terminal_market_reader (the publisher's group) may read the intraday bars, their quality, the change record and
--   Equity_Market_Schedule (the exchange time zone).
-- Rollback: DROP TABLE public.intraday_publish_change; restore the function from 20261031_004; DROP FUNCTION
-- public.intraday_bars_per_year(text); REVOKE the grants below; DELETE the catalog rows below.
BEGIN;

CREATE OR REPLACE FUNCTION public.intraday_bars_per_year(p_timeframe text)
RETURNS integer
LANGUAGE sql
STABLE
AS $fn$
-- Bars per year of an intraday timeframe: 252 x the mean IHSG bars of its COMPLETE sessions; NULL without one.
SELECT round(252 * avg(index_bars))::integer
  FROM public.price_stock_idx_intraday_quality
 WHERE timeframe = p_timeframe AND status = 'COMPLETE' AND index_bars > 0
$fn$;
COMMENT ON FUNCTION public.intraday_bars_per_year(text) IS
 'Bars per year of an intraday timeframe (5m, 15m, 1h, 4h): round(252 x mean IHSG bars of the COMPLETE sessions in price_stock_idx_intraday_quality); NULL when the timeframe has no COMPLETE session. Used by refresh_feature_01_stock_intraday and terminal-publisher.';

"""

TAIL = """
CREATE TABLE IF NOT EXISTS public.intraday_publish_change (
    ticker text NOT NULL,
    timeframe text NOT NULL CHECK (timeframe IN ('5m', '15m', '1h', '4h')),
    changed_from timestamptz NOT NULL,
    changed_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    PRIMARY KEY (ticker, timeframe)
);
COMMENT ON TABLE public.intraday_publish_change IS
 'Per ticker and timeframe the first bar idx-intraday-cron wrote (inserted or changed) since the last publication, and when; written in the same statement as the bars, IHSG included. terminal-publisher republishes the intraday files of the rows changed since its last run (EXEC-INTRADAY-FEATURES C7.4 A).';

DO $grant$ BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'terminal_market_reader') THEN
        GRANT SELECT ON public.price_stock_idx_intraday, public.price_stock_idx_intraday_quality,
              public.intraday_publish_change, public."Equity_Market_Schedule" TO terminal_market_reader;
        GRANT EXECUTE ON FUNCTION public.intraday_bars_per_year(text) TO terminal_market_reader;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'pgweb_reader') THEN
        GRANT SELECT ON public.intraday_publish_change TO pgweb_reader;
    END IF;
END $grant$;

INSERT INTO public."Table_Catalog"(table_schema, table_name, category, definition, grain, primary_key_columns,
 source_system, source_tables, source_code_paths, update_rule, related_functions, documentation_status,
 readiness_mode, readiness_date_column, observation_date_column, availability_rule, point_in_time_status)
VALUES
('public', 'intraday_publish_change', 'System', 'Per ticker and timeframe the first intraday bar the loader wrote (inserted or changed) since the last publication, and when: the change record terminal-publisher reads to republish only the intraday files that changed. IHSG included.', 'One ticker and timeframe', ARRAY['ticker', 'timeframe']::text[], 'apps/idx-price-cron/intraday_update.py', ARRAY['price_stock_idx_intraday']::text[], ARRAY['database/migrations/20261101_001_intraday_publish.sql', 'apps/idx-price-cron/intraday_update.py', 'apps/terminal-publisher/publisher.py']::text[], 'Written with the bars in the same statement; changed_from keeps the earliest bar written within the last 14 days (an older record is replaced); read by terminal-publisher.', ARRAY[]::text[], 'VERIFIED', 'NOT_APPLICABLE', NULL, NULL, 'Operational record, not market data; not exposed to the AI.', 'NOT_APPLICABLE')
ON CONFLICT (table_schema, table_name) DO NOTHING;

WITH d(column_name, definition, unit, null_rule) AS (VALUES
 ('ticker', 'Ticker of the series (stock or IHSG).', 'code', 'Never NULL.'),
 ('timeframe', 'Bar length of the series: 5m, 15m, 1h or 4h.', 'interval', 'Never NULL.'),
 ('changed_from', 'Open time of the first bar written since the last publication (the earliest within the last 14 days).', 'timestamp', 'Never NULL.'),
 ('changed_at', 'Time of the last write of the series.', 'timestamp', 'Never NULL.'))
INSERT INTO public."Column_Catalog"(table_schema, table_name, column_name, ordinal_position, data_type, is_nullable,
 default_expression, is_primary_key, definition, source_column_or_expression, unit, null_rule, source_code_paths,
 documentation_status)
SELECT 'public', c.table_name, c.column_name, c.ordinal_position, c.data_type, c.is_nullable = 'YES', c.column_default,
 c.column_name IN ('ticker', 'timeframe'), d.definition, 'apps/idx-price-cron/intraday_update.py (write_rows)',
 d.unit, d.null_rule, ARRAY['database/migrations/20261101_001_intraday_publish.sql'], 'VERIFIED'
FROM information_schema.columns c JOIN d USING (column_name)
WHERE c.table_schema = 'public' AND c.table_name = 'intraday_publish_change'
ON CONFLICT (table_schema, table_name, column_name) DO NOTHING;

UPDATE public."Table_Catalog"
   SET related_functions = array_append(related_functions, 'intraday_bars_per_year(text)')
 WHERE table_schema = 'public' AND table_name IN ('Feature_01_Stock_Intraday', 'price_stock_idx_intraday_quality')
   AND NOT ('intraday_bars_per_year(text)' = ANY (coalesce(related_functions, ARRAY[]::text[])));

COMMIT;
"""


def main():
    src = SRC.read_text()
    m = re.search(r"CREATE OR REPLACE FUNCTION public\.refresh_feature_01_stock_intraday\(.*?\$fn\$;\n", src, re.S)
    fn = m.group(0)
    if fn.count(INLINE) != 1:
        raise SystemExit('the inline bars_per_year statement was not found exactly once')
    fn = fn.replace(INLINE, CALL)
    OUT.write_text(HEAD + fn + TAIL)
    print(f'{OUT.relative_to(ROOT)}: {len(HEAD + fn + TAIL):,} bytes')


if __name__ == '__main__':
    main()
