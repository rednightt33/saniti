const cum = (n: number, step: (i: number) => number, start = 0): Series => { const o = nul(n); let acc = start; for(let i = 0; i < n; i++){ const d = step(i); if(isN(d)) acc += d; o[i] = acc } return o };
const mfm = (B: Seg): number[] => B.C.map((c, i) => B.H[i] === B.L[i] ? 0 : ((c - B.L[i]) - (B.H[i] - c)) / (B.H[i] - B.L[i]));
function adStep(B: Seg, i: number, ad: number): number {                // TA-Lib CALCULATE_AD
  const h = B.H[i], l = B.L[i], t = h - l, c = B.C[i];
  return t > 0.0 ? ad + (((c - l) - (h - c)) / t) * B.V[i] : ad;
}
function kPo(x: number[], p: Params) {                                  // TA_INT_PO with EMA, percentage output
  const f = kEma(x, p.fast_length), s = kEma(x, p.slow_length);
  const main: Series = f.map((v, i) => { const w = s[i]; return isN(v) && isN(w) ? (!isZero(w) ? ((v - w) / w) * 100.0 : 0.0) : null });
  const signal = runs(main, m => kEma(m, p.signal_length));
  return { main, signal, hist:main.map((v, i) => sub(v, signal[i])) };
}
function atrBy(B: Seg, n: number, type = 'RMA'): Series {
  if(type === 'RMA' || !type) return kAtr(B.H, B.L, B.C, n);
  const tr = kTr(B.H, B.L, B.C), k = type === 'SMA' ? kSma : type === 'EMA' ? kEma : type === 'WMA' ? kWma : null;
  return k ? runs(tr, x => k(x, n)) : kAtr(B.H, B.L, B.C, n);
}
function bands(B: Seg, p: Params) {                                     // TA-Lib BBANDS (other basis types keep the SMA-centred stdev)
  const x = srcOf(B, p.source), n = p.length, t = p.basis_ma_type;
  const basis = t === 'EMA' ? runs(x, v => kEma(v, n)) : t === 'WMA' ? runs(x, v => kWma(v, n)) : t === 'RMA' ? rma(x, n) : t === 'VWMA' ? vwmaOf(x, B.V, n) : runs(x, v => kSma(v, n));
  const sd = runs(x, v => kStd(v, n)), k = p.std_dev;
  const dev = (i: number) => k === 1.0 ? sd[i] as number : (sd[i] as number) * k;
  return {
    x, basis,
    upper:basis.map((v, i) => isN(v) && isN(sd[i]) ? v + dev(i) : null),
    lower:basis.map((v, i) => isN(v) && isN(sd[i]) ? v - dev(i) : null),
  };
}
function periodKey(anchor: string, d: string): string {                // VWAP anchor bucket for a 'YYYY-MM-DD' bar
  const y = +d.slice(0, 4), m = +d.slice(5, 7);
  switch(anchor){
    case 'Week': { const t = Date.parse(d + 'T00:00:00Z'), wd = (new Date(t).getUTCDay() + 6) % 7; return 'W' + (t - wd * 864e5) }
    case 'Month': return d.slice(0, 7);
    case 'Quarter': return y + 'Q' + Math.ceil(m / 3);
    case 'Year': return '' + y;
    case 'Decade': return 'D' + Math.floor(y / 10);
    case 'Century': return 'C' + Math.floor(y / 100);
    default: return d;                                                   // Session = one daily bar on a daily chart
  }
}
