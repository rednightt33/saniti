const srcOf = (B: Seg, s: string): number[] => {
  const n = B.N;
  switch(s){
    case 'open': return B.O; case 'high': return B.H; case 'low': return B.L;
    case 'hl2':  return map(n, i => (B.H[i] + B.L[i]) / 2) as number[];
    case 'hlc3': return map(n, i => (B.H[i] + B.L[i] + B.C[i]) / 3) as number[];
    case 'ohlc4': return map(n, i => (B.O[i] + B.H[i] + B.L[i] + B.C[i]) / 4) as number[];
    default: return B.C;
  }
};
