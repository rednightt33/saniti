/* ==========================================================================
   Technical indicators of the EDGE terminal (T1): the 53 registry keys I01-I53.
   Pure calculations, no DOM. Drop-in replacement for the reference engine `TA`
   of 03-terminal-right-panel.html: `F[key](bars, params)` returns
   `{ outputKey: (number|null)[] }` aligned with the bars (null = warm-up or undefined);
   `vwap` also returns `_breaks` (bar indices where an anchored period restarts).

   Conventions: verification/terminal_api/INDICATOR_SPEC.md (generated by
   scripts/terminal_indicator_spec.py). Each indicator names its source:
     FEATURE_04  equals Feature 04 / TA-Lib 0.6.8 exactly (same first valid bar, same seeds);
     TA_LIB      equals TA-Lib 0.6.8 with the stated function;
     HTML        equals the reference engine, except where the spec states a convention.
   The TA-Lib kernels (prefix `k`) repeat TA-Lib's own order of operations, so the results
   are the same doubles, not only close; the exported helpers (sma, ema, rma, wma, stdev)
   keep the reference engine's semantics and arithmetic for the HTML indicators.

   Bars: chronological final daily bars. A bar whose inputs needed by an indicator are not
   finite breaks the series: the outputs are null on it and the calculation restarts after
   it (Feature 04 resets its histories the same way). Parameters missing from `p` take the
   registry defaults; an invalid length (< 1 or not a number) gives all-null outputs.
   Tests: tests/calc (parity with Feature 04, TA-Lib and the reference engine; PARITY.md).
   ========================================================================== */

export type Num = number | null;
export type Series = Num[];
type In = ReadonlyArray<number | null | undefined>;
export interface Bars { O: In; H: In; L: In; C: In; V: In; T?: ReadonlyArray<string> }
export type Params = Record<string, any>;
export type Out = Record<string, Series> & { _breaks?: number[] };
export type IndicatorFn = (B: Bars, p?: Params) => Out;

/* ---- reference helpers (same semantics and arithmetic as the reference engine) ---- */
export const isN = (v: unknown): v is number => typeof v === 'number' && Number.isFinite(v);
const nul = (n: number): Series => new Array(n).fill(null);
const map = (n: number, f: (i: number) => Num | undefined): Series => { const o = nul(n); for(let i = 0; i < n; i++){ const v = f(i); o[i] = isN(v) ? v : null } return o };
const div = (a: Num | undefined, b: Num | undefined): Num => isN(a) && isN(b) && b !== 0 ? a / b : null;
const sub = (a: Num | undefined, b: Num | undefined): Num => isN(a) && isN(b) ? a - b : null;

/* rolling window over the last n valid, consecutive values */
function roll(x: In, n: number, f: (i: number) => Num): Series {
  const o = nul(x.length); let run = 0;
  for(let i = 0; i < x.length; i++){ run = isN(x[i]) ? run + 1 : 0; if(run >= n) o[i] = f(i) }
  return o;
}
/** Simple moving average; a null restarts the window. */
export function sma(x: In, n: number): Series {
  const o = nul(x.length); let s = 0, run = 0;
  for(let i = 0; i < x.length; i++){
    const v = x[i];
    if(!isN(v)) { s = 0; run = 0; continue }
    s += v; run++; if(run > n) s -= x[i - n] as number;
    if(run >= n) o[i] = s / n;
  }
  return o;
}
const sum = (x: In, n: number): Series => sma(x, n).map(v => v === null ? null : v * n);
function ewm(x: In, n: number, a: number): Series {
  const o = nul(x.length); let prev: number | null = null, s = 0, c = 0;
  for(let i = 0; i < x.length; i++){
    const v = x[i]; if(!isN(v)) { if(prev === null) { s = 0; c = 0 } continue }
    if(prev === null) { s += v; c++; if(c === n) { prev = s / n; o[i] = prev } }
    else { prev = a * v + (1 - a) * prev; o[i] = prev }
  }
  return o;
}
/** EMA seeded with the SMA of the first n valid values (nulls before the seed restart it, later ones are skipped). */
export const ema = (x: In, n: number): Series => ewm(x, n, 2 / (n + 1));
/** Wilder's running average (alpha 1/n), seeded like ema. */
export const rma = (x: In, n: number): Series => ewm(x, n, 1 / n);
/** Linearly weighted moving average (newest weight n). */
export const wma = (x: In, n: number): Series => { const den = n * (n + 1) / 2; return roll(x, n, i => { let s = 0; for(let j = 0; j < n; j++) s += (x[i - j] as number) * (n - j); return s / den }) };
/** Rolling standard deviation around the window mean (population unless sample). */
export const stdev = (x: In, n: number, sample = false): Series => roll(x, n, i => {
  let m = 0; for(let j = 0; j < n; j++) m += x[i - j] as number; m /= n;
  let s = 0; for(let j = 0; j < n; j++) s += ((x[i - j] as number) - m) ** 2;
  return sample ? (n > 1 ? Math.sqrt(s / (n - 1)) : null) : Math.sqrt(s / n);
});
const vwmaOf = (x: In, V: In, n: number): Series => { const a = sma(x.map((v, i) => isN(v) && isN(V[i]) ? v * (V[i] as number) : null), n), b = sma(V, n); return a.map((v, i) => div(v, b[i])) };
const highest = (x: In, n: number): Series => roll(x, n, i => { let m = -Infinity; for(let j = 0; j < n; j++) m = Math.max(m, x[i - j] as number); return m });
const lowest  = (x: In, n: number): Series => roll(x, n, i => { let m = Infinity;  for(let j = 0; j < n; j++) m = Math.min(m, x[i - j] as number); return m });
const change = (x: In, k = 1): Series => x.map((v, i) => i >= k ? sub(v, x[i - k]) : null);

/* ---- TA-Lib 0.6.8 kernels: a finite run in, TA-Lib's doubles out (same order of operations) ---- */
const EPS = 1e-14;                                                      // TA_EPSILON of TA-Lib 0.6.x (measured: RSI, STDDEV)
const isZero = (v: number) => -EPS < v && v < EPS;                      // TA_IS_ZERO
const isZeroOrNeg = (v: number) => v < EPS;                             // TA_IS_ZERO_OR_NEG
type Kernel = (x: number[]) => Series;
/** Applies a kernel to each run of finite values (a null restarts it, as TA-Lib on a fresh array). */
function runs(x: In, k: Kernel): Series {
  const N = x.length, o = nul(N); let s = 0;
  while(s < N){
    while(s < N && !isN(x[s])) s++;
    let e = s; while(e < N && isN(x[e])) e++;
    if(e > s){ const r = k((s === 0 && e === N ? x : x.slice(s, e)) as number[]); for(let i = 0; i < r.length; i++) o[s + i] = r[i] }
    s = e;
  }
  return o;
}
function kSma(x: number[], n: number): Series {                        // TA_INT_SMA
  const N = x.length, o = nul(N); if(N < n) return o;
  let t = 0; for(let i = 0; i < n - 1; i++) t += x[i];
  for(let i = n - 1; i < N; i++){ t += x[i]; o[i] = t / n; t -= x[i - n + 1] }
  return o;
}
function kEma(x: number[], n: number): Series {                        // TA_INT_EMA, SMA seed
  const N = x.length, o = nul(N); if(N < n) return o;
  const k = 2 / (n + 1); let t = 0; for(let i = 0; i < n; i++) t += x[i];
  let prev = t / n; o[n - 1] = prev;
  for(let i = n; i < N; i++){ prev = (x[i] - prev) * k + prev; o[i] = prev }
  return o;
}
function kWma(x: number[], n: number): Series {                        // TA_WMA
  const N = x.length, o = nul(N); if(N < n) return o;
  if(n === 1) return x.slice();
  const dv = (n * (n + 1)) >> 1; let pSub = 0, pSum = 0, tv = 0, tr = 0, i = 0;
  for(; i < n - 1; i++){ pSub += x[i]; pSum += x[i] * (i + 1) }
  for(; i < N; i++){ pSub += x[i]; pSub -= tv; pSum += x[i] * n; tv = x[tr++]; o[i] = pSum / dv; pSum -= pSub }
  return o;
}
function kStd(x: number[], n: number): Series {                        // TA_STDDEV (TA_INT_VAR), nbdev 1
  const N = x.length, o = nul(N); if(N < n) return o;
  let t1 = 0, t2 = 0, tr = 0;
  for(let i = 0; i < n - 1; i++){ t1 += x[i]; t2 += x[i] * x[i] }
  for(let i = n - 1; i < N; i++){
    t1 += x[i]; t2 += x[i] * x[i];
    const m1 = t1 / n, m2 = t2 / n, old = x[tr++];
    t1 -= old; t2 -= old * old;
    const v = m2 - m1 * m1; o[i] = isZeroOrNeg(v) ? 0 : Math.sqrt(v);
  }
  return o;
}
function kMax(x: number[], n: number): Series { const o = nul(x.length); for(let i = n - 1; i < x.length; i++){ let m = x[i - n + 1]; for(let j = i - n + 2; j <= i; j++) if(x[j] > m) m = x[j]; o[i] = m } return o }
function kMin(x: number[], n: number): Series { const o = nul(x.length); for(let i = n - 1; i < x.length; i++){ let m = x[i - n + 1]; for(let j = i - n + 2; j <= i; j++) if(x[j] < m) m = x[j]; o[i] = m } return o }
/** True range from the second bar (TA_TRANGE: none on the first bar). */
function kTr(H: number[], L: number[], C: number[]): Series {
  return map(C.length, i => i ? Math.max(H[i] - L[i], Math.abs(C[i - 1] - H[i]), Math.abs(C[i - 1] - L[i])) : null);
}
function kAtr(H: number[], L: number[], C: number[], n: number): Series { // TA_ATR: SMA of the first n TR, then Wilder
  const N = C.length, tr = kTr(H, L, C); if(n <= 1) return tr;
  const o = nul(N); if(N <= n) return o;
  let t = 0; for(let i = 1; i < n; i++) t += tr[i] as number;
  t += tr[n] as number; let prev = t / n; o[n] = prev;
  for(let i = n + 1; i < N; i++){ prev *= n - 1; prev += tr[i] as number; prev /= n; o[i] = prev }
  return o;
}
function kRsi(x: number[], n: number): Series {                        // TA_RSI: 100*gain/(gain+loss), 0 when both are 0
  const N = x.length, o = nul(N); if(N <= n) return o;
  let prevV = x[0], g = 0, l = 0, t = 1;
  for(let i = n; i > 0; i--){ const v = x[t++], d = v - prevV; prevV = v; if(d < 0) l -= d; else g += d }
  l /= n; g /= n;
  let s = g + l; o[n] = isZero(s) ? 0 : 100 * (g / s);
  for(; t < N; t++){
    const v = x[t], d = v - prevV; prevV = v;
    l *= n - 1; g *= n - 1; if(d < 0) l -= d; else g += d; l /= n; g /= n;
    s = g + l; o[t] = isZero(s) ? 0 : 100 * (g / s);
  }
  return o;
}
/** TA-Lib STOCHF fast %K of x within [lo, hi] windows of n: 0 on a zero range. */
function kFastK(x: number[], hi: number[], lo: number[], n: number, start = 0): Series {
  const o = nul(x.length);
  for(let i = start + n - 1; i < x.length; i++){
    let h = hi[i - n + 1], l = lo[i - n + 1];
    for(let j = i - n + 2; j <= i; j++){ if(hi[j] > h) h = hi[j]; if(lo[j] < l) l = lo[j] }
    const d = (h - l) / 100.0; o[i] = d !== 0.0 ? (x[i] - l) / d : 0.0;
  }
  return o;
}
/** Wilder DMI (TA_PLUS_DI / TA_MINUS_DI / TA_ADX), di length d, ADX smoothing a. */
function kDmi(H: number[], L: number[], C: number[], d: number, a: number) {
  const N = C.length, plus = nul(N), minus = nul(N), adx = nul(N);
  if(N <= d) return { plus, minus, adx };
  let pH = H[0], pL = L[0], pC = C[0], pDM = 0, mDM = 0, tr = 0, sumDX = 0, nDX = 0, prevADX = 0;
  for(let i = 1; i < N; i++){
    const dP = H[i] - pH, dM = pL - L[i]; pH = H[i]; pL = L[i];
    const t = Math.max(pH - pL, Math.abs(pC - pH), Math.abs(pC - pL)); pC = C[i];
    if(i < d){ if(dM > 0 && dP < dM) mDM += dM; else if(dP > 0 && dP > dM) pDM += dP; tr += t; continue }
    pDM -= pDM / d; mDM -= mDM / d;
    if(dM > 0 && dP < dM) mDM += dM; else if(dP > 0 && dP > dM) pDM += dP;
    tr = tr - (tr / d) + t;
    let dx: number | null = null;
    if(!isZero(tr)){
      const mi = 100.0 * (mDM / tr), pi = 100.0 * (pDM / tr), s = mi + pi;
      plus[i] = pi; minus[i] = mi;
      if(!isZero(s)) dx = 100.0 * (Math.abs(mi - pi) / s);
    } else { plus[i] = 0; minus[i] = 0 }
    if(nDX < a){                                                         // seed: mean of the first a DX (a missing DX counts 0)
      if(dx !== null) sumDX += dx;
      if(++nDX === a){ prevADX = sumDX / a; adx[i] = prevADX }
    } else {                                                             // a missing DX keeps the previous ADX
      if(dx !== null) prevADX = ((prevADX * (a - 1)) + dx) / a;
      adx[i] = prevADX;
    }
  }
  return { plus, minus, adx };
}

