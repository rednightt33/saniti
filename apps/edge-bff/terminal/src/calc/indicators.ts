const LENGTH_KEYS = /(^|_)(length|smoothing|smooth_k|smooth_d|periods)$/;
/**
 * Wraps an indicator: merges defaults, checks lengths (integers >= 1, floored) and numeric
 * parameters, then runs `calc` on each segment of bars whose `need` inputs are finite.
 */
function def(key: string, outs: string[], need: (p: Params) => string, calc: (B: Seg, p: Params) => Out): IndicatorFn {
  return (B, p0 = {}) => {
    const p: Params = { ...DEFAULTS[key], ...p0 }, N = B.C.length, res: Out = {};
    for(const k of outs) res[k] = nul(N);
    for(const [k, v] of Object.entries(p)){
      if(LENGTH_KEYS.test(k)){ const n = Math.floor(Number(v)); if(!(n >= 1)) return res; p[k] = n }
      else if(typeof DEFAULTS[key][k] === 'number'){ const x = Number(v); if(!Number.isFinite(x)) return res; p[k] = x }
    }
    const fields = need(p), cols = ['O', 'H', 'L', 'C', 'V'].filter(f => fields.includes(f)) as (keyof Bars)[];
    const ok = (i: number) => cols.every(f => isN((B[f] as In)[i]));
    const breaks: number[] = [];
    let s = 0, first = true;
    while(s < N){
      while(s < N && !ok(s)) s++;
      let e = s; while(e < N && ok(e)) e++;
      if(e > s){
        const whole = s === 0 && e === N, cut = (a: In | undefined) => (a ? (whole ? a : a.slice(s, e)) : []) as number[];
        const seg: Seg = { O:cut(B.O), H:cut(B.H), L:cut(B.L), C:cut(B.C), V:cut(B.V), T:(B.T ? (whole ? B.T : B.T.slice(s, e)) : []) as string[], N:e - s };
        const r = calc(seg, p);
        for(const k of outs){ const a = r[k], o = res[k]; if(a) for(let i = 0; i < a.length; i++){ const v = a[i]; o[s + i] = isN(v) ? v : null } }
        if(!first) breaks.push(s);
        if(r._breaks) for(const b of r._breaks) breaks.push(s + b);
        first = false;
      }
      s = e;
    }
    if(key === 'vwap') res._breaks = breaks;
    return res;
  };
}
